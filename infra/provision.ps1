#requires -Version 7.0
<#
.SYNOPSIS
    Provisions the Voice of the Game environment with the Azure CLI.

.DESCRIPTION
    Creates or updates the resource group, deploys infra/main.bicep, and writes the non-secret
    endpoints to .env.local at the repository root (git-ignored) for local development.
    The AI resource has key auth disabled: apps authenticate with DefaultAzureCredential, so the
    signed-in developer is granted the Speech, Cognitive Services and Foundry data-plane roles.
    Safe to re-run: every step is idempotent.

.EXAMPLE
    ./infra/provision.ps1

.EXAMPLE
    ./infra/provision.ps1 -Environment demo -Location swedencentral -Subscription "My subscription"
#>
[CmdletBinding()]
param(
    [ValidatePattern('^[a-z0-9]{1,8}$')]
    [string] $Environment = 'dev',

    [string] $Location = 'swedencentral',

    [string] $ResourceGroup,

    [string] $Subscription
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

if (-not $ResourceGroup) {
    $ResourceGroup = "rg-vog-$Environment"
}

function Invoke-Az {
    $output = & az @args
    if ($LASTEXITCODE -ne 0) {
        throw "az $($args -join ' ') failed with exit code $LASTEXITCODE."
    }

    return $output
}

if (-not (Get-Command az -ErrorAction SilentlyContinue)) {
    throw 'The Azure CLI (az) is not installed. See https://aka.ms/installazurecli'
}

if ($Subscription) {
    Invoke-Az account set --subscription $Subscription | Out-Null
}

$account = Invoke-Az account show --query '{name:name, user:user.name}' --output json | ConvertFrom-Json
Write-Host "Subscription   : $($account.name)"
Write-Host "Signed in as   : $($account.user)"
Write-Host "Region         : $Location"
Write-Host "Resource group : $ResourceGroup"

$principalId = Invoke-Az ad signed-in-user show --query id --output tsv

Write-Host "`n[1/3] Resource group"
Invoke-Az group create --name $ResourceGroup --location $Location --tags project=voice-of-the-game environment=$Environment --output none

Write-Host '[2/3] Deploying infra/main.bicep (a few minutes the first time)'
$outputs = Invoke-Az deployment group create `
    --resource-group $ResourceGroup `
    --name "vog-$Environment-$(Get-Date -Format 'yyyyMMdd-HHmmss')" `
    --template-file (Join-Path $PSScriptRoot 'main.bicep') `
    --parameters environmentName=$Environment developerPrincipalId=$principalId `
    --query properties.outputs `
    --output json | ConvertFrom-Json

Write-Host '[3/3] Writing .env.local (git-ignored; endpoints only, no keys)'
$repoRoot = Split-Path $PSScriptRoot -Parent
$lines = @('# Generated by infra/provision.ps1. Endpoints only: the AI resource has key auth disabled.')
foreach ($output in $outputs.PSObject.Properties) {
    # The CLI camel-cases output names (AZURE_LOCATION -> azurE_LOCATION); they are UPPER_SNAKE by design.
    $lines += "$($output.Name.ToUpperInvariant())=$($output.Value.value)"
}

Set-Content -Path (Join-Path $repoRoot '.env.local') -Value $lines -Encoding utf8NoBOM

Write-Host "`nDone. New role assignments can take a few minutes to take effect."
foreach ($output in $outputs.PSObject.Properties) {
    Write-Host ('  {0,-30} {1}' -f $output.Name.ToUpperInvariant(), $output.Value.value)
}
